    private void loginBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginBtnActionPerformed
        String username = usernameTxt.getText();
        char rawPass[]= passwordField.getPassword();
        String password = String.valueOf(rawPass); //converts into raw pass

        // Validation: both boxes must be filled in
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter username and password");
            return;
        }

        try{
            FileReader fr = new FileReader("src/data/users.txt");
            BufferedReader br = new BufferedReader(fr);

            String line;
            boolean found = false;

            while((line=br.readLine())!=null){
                // users.txt line: id,username,password,name,phone,role
                String parts[] = line.split(",");
                if (username.equals(parts[1]) && password.equals(parts[2])) {
                    found = true;
                    LoggedIn.setUserId(parts[0]);
                    LoggedIn.setUsername(parts[1]);
                    LoggedIn.setName(parts[3]);
                    LoggedIn.setRole(parts[5]);
                    break;
                }
            }
            br.close();

            if(!found){
                JOptionPane.showMessageDialog(null,"Invalid Username or Password");
            } else {
                JOptionPane.showMessageDialog(null, "Login Successful!");

                // Open the dashboard that matches the role
                String role = LoggedIn.getRole();
                if (role.equals("Manager")) {
                    new ManagerDashboard().setVisible(true);
                } else if (role.equals("Administrator")) {
                    new AdminDashboard().setVisible(true);
                } else if (role.equals("Instructor")) {
                    new InstructorDashboard().setVisible(true);
                } else if (role.equals("Student")) {
                    new StudentDashboard().setVisible(true);
                } else if (role.equals("FacilitiesOfficer")) {
                    new FacilitiesOfficerDashboard().setVisible(true);
                } else if (role.equals("AttendanceOfficer")) {
                    new AttendanceOfficerDashboard().setVisible(true);
                }
                this.dispose(); //close current form
            }
        }catch(IOException e){
            JOptionPane.showMessageDialog(null, "Cannot read users.txt");
        }
    }//GEN-LAST:event_loginBtnActionPerformed

