    // Shows staffs in the table.
    // keyword = text typed in the search box ("" shows everyone)
    private void loadTable(String keyword) {
        DefaultTableModel model = (DefaultTableModel) staffTable.getModel();
        model.setRowCount(0); // remove old rows first
        keyword = keyword.toLowerCase();

        for (User user : UserFile.readAll()) {
            // instanceof checks which child class the object really is
            if (user instanceof Instructor || user instanceof FacilitiesOfficer) {
                if (user.getId().toLowerCase().contains(keyword)
                        || user.getUsername().toLowerCase().contains(keyword)
                        || user.getName().toLowerCase().contains(keyword)
                        || user.getRole().toLowerCase().contains(keyword)) {
                    model.addRow(new Object[]{user.getId(), user.getUsername(), user.getPassword(),
                        user.getName(), user.getPhone(), user.getRole()});
                }
            }
        }
    }

    // Checks the input boxes. Returns true if everything is OK.
    private boolean validateInputs() {
        String username = usernameTxt.getText().trim();
        String password = passwordTxt.getText().trim();
        String name = nameTxt.getText().trim();
        String phone = phoneTxt.getText().trim();

        if (username.isEmpty() || password.isEmpty() || name.isEmpty() || phone.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill in all fields");
            return false;
        }
        if ((username + password + name + phone).contains(",")) {
            JOptionPane.showMessageDialog(null, "Commas (,) are not allowed");
            return false;
        }
        if (username.contains(" ")) {
            JOptionPane.showMessageDialog(null, "Username cannot contain spaces");
            return false;
        }
        if (password.length() < 3) {
            JOptionPane.showMessageDialog(null, "Password must be at least 3 characters");
            return false;
        }
        if (!name.matches("[a-zA-Z ]+")) {
            JOptionPane.showMessageDialog(null, "Name can only contain letters and spaces");
            return false;
        }
        if (!phone.matches("[0-9]{10,11}")) {
            JOptionPane.showMessageDialog(null, "Phone must be 10 or 11 digits, e.g. 0123456789");
            return false;
        }
        return true;
    }

    // Empties all the boxes so a new staff can be added
    private void clearFields() {
        idTxt.setText("");
        usernameTxt.setText("");
        passwordTxt.setText("");
        nameTxt.setText("");
        phoneTxt.setText("");
        roleCombo.setSelectedIndex(0);
        roleCombo.setEnabled(true);
        staffTable.clearSelection();
    }

    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
        if (!idTxt.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "This staff already exists. Click Clear to add a new one.");
            return;
        }
        if (!validateInputs()) {
            return;
        }
        String username = usernameTxt.getText().trim();
        if (UserFile.usernameExists(username, "")) {
            JOptionPane.showMessageDialog(null, "Username already taken");
            return;
        }

        String password = passwordTxt.getText().trim();
        String name = nameTxt.getText().trim();
        String phone = phoneTxt.getText().trim();
        String role = roleCombo.getSelectedItem().toString();

        // A Staff variable can hold an Instructor OR a FacilitiesOfficer (inheritance)
        Staff staff;
        if (role.equals("Instructor")) {
            staff = new Instructor(UserFile.nextId("IN"), username, password, name, phone);
        } else {
            staff = new FacilitiesOfficer(UserFile.nextId("FO"), username, password, name, phone);
        }
        UserFile.add(staff);

        JOptionPane.showMessageDialog(null, "Staff added. ID: " + staff.getId());
        clearFields();
        loadTable("");
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        String id = idTxt.getText();
        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please select a staff from the table first");
            return;
        }
        if (!validateInputs()) {
            return;
        }
        String username = usernameTxt.getText().trim();
        if (UserFile.usernameExists(username, id)) {
            JOptionPane.showMessageDialog(null, "Username already taken");
            return;
        }

        // Load everyone, change the matching user with setters, save everyone back
        ArrayList<User> users = UserFile.readAll();
        for (User user : users) {
            if (user.getId().equals(id)) {
                user.setUsername(username);
                user.setPassword(passwordTxt.getText().trim());
                user.setName(nameTxt.getText().trim());
                user.setPhone(phoneTxt.getText().trim());
            }
        }
        UserFile.writeAll(users);

        JOptionPane.showMessageDialog(null, "Staff updated");
        clearFields();
        loadTable("");
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        String id = idTxt.getText();
        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please select a staff from the table first");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(null, "Delete " + id + "?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        // Load everyone, remove the matching user, save everyone back
        ArrayList<User> users = UserFile.readAll();
        for (int i = 0; i < users.size(); i++) {
            if (users.get(i).getId().equals(id)) {
                users.remove(i);
                break;
            }
        }
        UserFile.writeAll(users);

        JOptionPane.showMessageDialog(null, "Staff deleted");
        clearFields();
        loadTable("");
    }//GEN-LAST:event_deleteBtnActionPerformed

