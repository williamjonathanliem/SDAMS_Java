    // payments.txt line: paymentId,studentId,bookingId,amount,date,method
    // e.g. P001,ST001,B001,80.00,2026-10-05,Card   (date is yyyy-mm-dd)
    private static final String FILE = "src/data/payments.txt";

    // Shows the payments that match the search box, month and year
    private void loadTable() {
        DefaultTableModel model = (DefaultTableModel) paymentTable.getModel();
        model.setRowCount(0); // remove old rows first

        String keyword = searchTxt.getText().trim().toLowerCase();
        int month = monthCombo.getSelectedIndex(); // 0 = All, 1 = January ... 12 = December
        String year = yearTxt.getText().trim();

        if (!year.isEmpty() && !year.matches("[0-9]{4}")) {
            JOptionPane.showMessageDialog(null, "Year must be 4 digits, e.g. 2026");
            return;
        }

        ArrayList<User> users = UserFile.readAll(); // used to find each student's name
        int count = 0;
        double total = 0;

        try {
            FileReader fr = new FileReader(FILE);
            BufferedReader br = new BufferedReader(fr);
            String line;
            while ((line = br.readLine()) != null) {
                String parts[] = line.split(",");
                if (parts.length < 6) {
                    continue; // skip empty or broken lines
                }
                String paymentId = parts[0];
                String studentId = parts[1];
                String bookingId = parts[2];
                String date = parts[4];
                String method = parts[5];
                String studentName = getStudentName(users, studentId);

                double amount;
                int paymentMonth;
                try {
                    amount = Double.parseDouble(parts[3]);
                    paymentMonth = Integer.parseInt(date.substring(5, 7)); // "2026-10-05" -> 10
                } catch (NumberFormatException | StringIndexOutOfBoundsException e) {
                    continue; // skip lines with a bad amount or date
                }

                boolean show = true;
                // Filter 1: search box matches payment ID, student ID or student name
                if (!keyword.isEmpty()
                        && !paymentId.toLowerCase().contains(keyword)
                        && !studentId.toLowerCase().contains(keyword)
                        && !studentName.toLowerCase().contains(keyword)) {
                    show = false;
                }
                // Filter 2: year
                if (!year.isEmpty() && !date.startsWith(year)) {
                    show = false;
                }
                // Filter 3: month
                if (month != 0 && paymentMonth != month) {
                    show = false;
                }

                if (show) {
                    model.addRow(new Object[]{paymentId, studentId, studentName, bookingId,
                        String.format("%.2f", amount), date, method});
                    count++;
                    total = total + amount;
                }
            }
            br.close();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(null, "Cannot read payments.txt");
        }

        totalLbl.setText("Total: " + count + " payment(s), RM " + String.format("%.2f", total));
    }

    // Finds the student's name from their ID
    private String getStudentName(ArrayList<User> users, String studentId) {
        for (User user : users) {
            if (user.getId().equals(studentId)) {
                return user.getName();
            }
        }
        return "(unknown)";
    }

